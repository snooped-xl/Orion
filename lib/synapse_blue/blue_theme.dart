    textStyle: blueText(10, family: family),
  ),
);

/// Default Inter line-box dimensions from the source ShellFitLine output.
class BlueHeading extends StatelessWidget {
  const BlueHeading(
    this.text, {
    super.key,
    required this.family,
    this.size = 22,
    this.lineBox = 31.234375,
    this.weight = FontWeight.w400,
    this.color = Colors.white,
  });
  final String text, family;
  final double size, lineBox;
  final FontWeight weight;
  final Color color;
  @override
  Widget build(BuildContext context) => SizedBox(
    height:
        lineBox + (MediaQuery.textScalerOf(context).scale(size) - size) * 1.42,
    child: Text(
      text,
      style: blueText(
        size,
        family: family,
        height: 1.42,
        weight: weight,
        color: color,
      ),
    ),
  );
}
