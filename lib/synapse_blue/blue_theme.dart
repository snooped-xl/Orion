  double size, {
  Color color = Colors.white,
  FontWeight weight = FontWeight.w400,
  double height = 1.2,
  String family = 'SynapseInter',
}) => TextStyle(
  fontFamily: family,
  fontSize: size,
  color: color,
  fontWeight: weight,
  letterSpacing: 0,
  height: height,
);

