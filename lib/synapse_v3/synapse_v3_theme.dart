class V3Colors extends ThemeExtension<V3Colors> {
  const V3Colors._(this.tokens);
  final Map<String, Color> tokens;

  factory V3Colors.fromColors({
    Color? background,
    Color? accent,
    bool legacyFramework = false,
    Map<String, int> overrides = const {},
  }) {
    final base = V3ThemePresets
        .colors[legacyFramework ? 'legacyFramework' : 'framework']!;
    final tokens = {
      for (final entry in base.entries) entry.key: Color(entry.value),
    };
    if (background != null) {
      tokens['shell.pageBg'] = background;
      tokens['shell.contentBg'] = background;
    }
    if (accent != null) {
      tokens['accent.primary'] = accent;
      tokens['accent.selectionBorder'] = accent;
      tokens['scriptHub.toggleIndicator'] = accent;
      tokens['settingsChrome.chipSelectedBorder'] = accent;
    }
    for (final entry in overrides.entries) {
      if (tokens.containsKey(entry.key)) tokens[entry.key] = Color(entry.value);
    }
    return V3Colors._(Map.unmodifiable(tokens));
  }

  static V3Colors of(BuildContext context) =>
      Theme.of(context).extension<V3Colors>() ?? V3Colors.fromColors();
  Color token(String name) => tokens[name] ?? Colors.white;
