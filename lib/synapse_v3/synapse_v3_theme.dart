abstract final class V3Type {
  static const interFamily = 'SynapseInter';
  static const rubikFamily = 'SynapseRubik';
  static TextStyle text(
    double size, {
    Color color = Colors.white,
    FontWeight weight = FontWeight.w400,
    double? height,
    String? family,
    double letterSpacing = 0,
  }) => TextStyle(
    fontFamily: family,
    fontSize: size,
    fontWeight: weight,
    color: color,
    height: height,
    letterSpacing: letterSpacing,
  );
  static TextStyle rubik(
    double size, {
    Color color = Colors.white,
    FontWeight weight = FontWeight.w400,
    double? height,
  }) => text(
    size,
    color: color,
    weight: weight,
    height: height,
    family: rubikFamily,
  );
}

abstract final class V3ThemeData {
  static ThemeData theme(
    Color accent,
    Color background, {
    bool legacyFramework = false,
    Map<String, int> overrides = const {},
    String family = V3Type.interFamily,
  }) {
    final c = V3Colors.fromColors(
      background: background,
      accent: accent,
      legacyFramework: legacyFramework,
      overrides: overrides,
    );
    return ThemeData(
      useMaterial3: false,
      brightness: Brightness.dark,
      fontFamily: family,
      splashFactory: NoSplash.splashFactory,
      highlightColor: Colors.transparent,
      scaffoldBackgroundColor: c.background,
      extensions: [c],
      colorScheme: ColorScheme.dark(
        primary: accent,
        secondary: c.accentMuted,
        surface: c.background,
        onSurface: c.text,
      ),
      textTheme: TextTheme(
        bodyMedium: V3Type.text(12, family: family),
        bodySmall: V3Type.text(10, color: c.muted, family: family),
      ),
      dividerTheme: DividerThemeData(color: c.divider, thickness: 1, space: 1),
      tooltipTheme: TooltipThemeData(
        decoration: BoxDecoration(
          color: c.settingsControl,
          borderRadius: BorderRadius.circular(4),
        ),
        textStyle: V3Type.text(11),
        waitDuration: const Duration(milliseconds: 400),
      ),
      textButtonTheme: TextButtonThemeData(
        style: TextButton.styleFrom(
          foregroundColor: c.text,
          padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 6),
          textStyle: V3Type.text(12),
          minimumSize: const Size(0, 0),
          shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(4)),
        ),
      ),
      inputDecorationTheme: InputDecorationTheme(
        isDense: true,
        filled: true,
        fillColor: c.settingsField,
        contentPadding: const EdgeInsets.symmetric(horizontal: 9, vertical: 7),
        hintStyle: V3Type.text(12, color: c.searchPlaceholder),
        border: OutlineInputBorder(
          borderRadius: BorderRadius.circular(4),
          borderSide: BorderSide(color: c.settingsFieldBorder),
        ),
      ),
      dialogTheme: DialogThemeData(
        backgroundColor: c.background,
        elevation: 0,
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(7)),
      ),
    );
  }
}
